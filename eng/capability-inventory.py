"""Generate the current implemented-tool inventory from contracts and host source."""
import argparse
import json
from pathlib import Path
import re


def render(root):
    tools = json.loads((root/'contracts/mcp-tools.v1.json').read_text(encoding='utf-8'))
    local = set(json.loads((root/'contracts/tool-access.v1.json').read_text())['localTools'])
    sources = {}
    for source in sorted((root/'src/hosts/PlcMcp.McpHost/Tools').glob('*.cs')):
        for name in re.findall(r'McpServerTool\(Name = "([a-z_]+)"', source.read_text(encoding='utf-8')):
            if name in sources: raise ValueError('Duplicate tool: '+name)
            sources[name] = source.relative_to(root).as_posix()
    names = {t['name'] for t in tools}
    if names != set(sources) or not local <= names: raise ValueError('Tool source, contract and access inventories differ.')
    lines = ['# 当前 MCP 工具清单', '', '<!-- Generated by eng/capability-inventory.py; do not edit rows manually. -->', '',
             f'P10 共 {len(names)} 个已实现工具，其中 {len(local)} 个本地工具。这里统计代码实现，不是厂商支持认证。', '',
             'TestHost 提供同契约模拟执行；ValidationHost 依显式白名单验证真实环境；生产宿主按验收范围开放 IDE 操作。',
             '所有汇川执行能力目前仍为 Unverified；本地 XML 生成与校验不证明 InoProShop 兼容。', '',
             '功能类别和未实现项见 [功能范围与缺口](23-capability-closure.md)，运行步骤见 [P10 交付说明](21-delivery-closure.md)。', '',
             '| 工具 | 执行要求 | 输入/输出契约 | 实现入口 |', '|---|---|---|---|']
    for tool in sorted(tools, key=lambda t:t['name']):
        name=tool['name']; source=sources[name]
        if not tool.get('inputSchema') or not tool.get('outputSchema'): raise ValueError('Missing schema: '+name)
        lines.append(f'| `{name}` | '+('本地；仍有参数/数据前提' if name in local else 'IDE；当前 Unverified')+
                     f' | [Schema](../contracts/mcp-tools.v1.json) | [{Path(source).stem}](../{source}) |')
    return '\n'.join(lines)+'\n'


def main():
    parser=argparse.ArgumentParser(); parser.add_argument('--write',action='store_true'); args=parser.parse_args()
    root=Path(__file__).resolve().parents[1]; target=root/'docs/22-current-tools.md'; expected=render(root)
    if args.write: target.write_text(expected,encoding='utf-8')
    elif not target.is_file() or target.read_text(encoding='utf-8') != expected: raise SystemExit('Current inventory drifted; run python eng/capability-inventory.py --write.')
    print('Current 74-tool implementation inventory matches source and schemas.')


if __name__=='__main__': main()
